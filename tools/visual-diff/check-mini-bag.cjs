const assert = require('node:assert/strict');
const { chromium } = require('playwright-core');
const base = 'http://localhost:8080';
(async () => {
 const browser = await chromium.launch({channel:'msedge'});
 const context = await browser.newContext({viewport:{width:1440,height:900}});
 const page = await context.newPage();
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base+'/product/arlene-outer-dress/',{waitUntil:'networkidle'});
 const url=page.url();
 for(const width of [1440,768,390]) {
  await page.setViewportSize({width,height:844});
  await page.locator('.single_add_to_cart_button').click();
  const modal=page.locator('#added-panel');
  await modal.locator('a.btn--primary').waitFor();
  await page.waitForTimeout(300);
  assert.equal(page.url(),url);
  assert(await modal.evaluate(e=>e.matches(':modal')));
  assert(await page.locator('.single_add_to_cart_button').isVisible());
  assert.match(await modal.innerText(),/Arlene Outer Dress/);
  const box=await modal.boundingBox();
  assert(Math.abs(box.x-(width<600?0:width-440))<1);
  assert(width<600 ? box.y>0 && Math.abs(box.y+box.height-844)<1 : box.y===0);
  const scroll=await page.evaluate(()=>scrollY);
  await page.mouse.move(5,5); await page.mouse.wheel(0,400); await page.waitForTimeout(100);
  assert.equal(await page.evaluate(()=>scrollY),scroll);
  await page.keyboard.press('Tab');
  assert(await modal.locator('.panel__close').evaluate(e=>e===document.activeElement));
  await page.keyboard.press('Shift+Tab');
  assert(await modal.locator('[data-panel-close]').last().evaluate(e=>e===document.activeElement));
  if(width===1440) await page.keyboard.press('Escape');
  else if(width===768) await page.mouse.click(10,10);
  else await modal.locator('[data-panel-close]').last().click();
  await modal.waitFor({state:'hidden'});
  assert(await page.locator('.single_add_to_cart_button').evaluate(e=>e===document.activeElement));
  console.log('PASS responsive, focus, scroll and close:',width);
 }
 await page.setViewportSize({width:1440,height:900});
 await page.goto(base+'/product/vale-dress/',{waitUntil:'networkidle'});
 await page.selectOption('.variations_form select','S');
 await page.locator('.single_add_to_cart_button:not(.disabled)').waitFor();
 await page.locator('.single_add_to_cart_button').click();
 await page.locator('#added-panel[open]').waitFor();
 assert.match(await page.locator('#added-panel').innerText(),/Size S/);
 await page.locator('#added-panel .panel__close').click();
 await page.locator('#added-panel').waitFor({state:'hidden'});
 await page.evaluate(()=>{const f=document.querySelector('form.cart');let q=f.querySelector('[name=quantity]');q.value='999999';f.requestSubmit();});
 await page.locator('[data-add-feedback] .woocommerce-error').waitFor();
 assert.equal(await page.locator('#added-panel').getAttribute('open'),null);
 console.log('PASS variation and server-side stock validation');
 await page.route('**/product/vale-dress/',route=>route.request().method()==='POST'?route.abort():route.continue());
 await page.evaluate(()=>{const f=document.querySelector('form.cart');f.querySelector('[name=quantity]').value='1';f.requestSubmit();});
 await page.locator('[data-add-feedback] a').waitFor();
 assert.match(await page.locator('[data-add-feedback]').innerText(),/Check your bag/);
 console.log('PASS network failure offers bag check without reposting');
 assert.deepEqual(errors,[]);
 const nojs=await browser.newContext({javaScriptEnabled:false});
 const fallback=await nojs.newPage();
 await fallback.goto(base+'/product/arlene-outer-dress/');
 await Promise.all([fallback.waitForURL('**/*added=*'),fallback.locator('.single_add_to_cart_button').click()]);
 assert(await fallback.locator('#added-panel[open]').isVisible());
 assert(await fallback.locator('.single_add_to_cart_button').isVisible());
 await fallback.locator('#added-panel [data-panel-close]').last().click();
 assert(!fallback.url().includes('added='));
 console.log('PASS no-JavaScript add and dismiss');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
